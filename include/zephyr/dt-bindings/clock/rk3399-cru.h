#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_RK3399_CRU_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_RK3399_CRU_H_

/*
 * RK3399 clock gates, encoded as (CLKGATE_CON index * 16) + bit.
 * CRU: CLKGATE_CON(n) at 0x300 + 4 * n, PMUCRU: at 0x100 + 4 * n.
 */
#define RK3399_CLK_GATE(con, bit) (((con) * 16) + (bit))

/* CRU */
#define SCLK_PCIE_PM		RK3399_CLK_GATE(6, 2)
#define SCLK_PCIE_CORE_CRU	RK3399_CLK_GATE(6, 3)
#define FCLK_CM0S_GPLL_SRC	RK3399_CLK_GATE(7, 5)
#define FCLK_CM0S_CPLL_SRC	RK3399_CLK_GATE(7, 6)
#define FCLK_CM0S		RK3399_CLK_GATE(7, 9)
#define SCLK_PCIEPHY_REF100M	RK3399_CLK_GATE(12, 6)
#define ACLK_PERF_PCIE		RK3399_CLK_GATE(20, 2)
#define ACLK_PCIE		RK3399_CLK_GATE(20, 10)
#define PCLK_PCIE		RK3399_CLK_GATE(20, 11)
#define SCLK_M0_PERILP		RK3399_CLK_GATE(24, 8)
#define HCLK_M0_PERILP		RK3399_CLK_GATE(24, 9)
#define DCLK_M0_PERILP		RK3399_CLK_GATE(24, 10)
#define SCLK_M0_PERILP_DEC	RK3399_CLK_GATE(24, 11)
#define HCLK_M0_PERILP_NOC	RK3399_CLK_GATE(25, 11)

/* PMUCRU */
#define PCLK_WDT_M0_PMU		RK3399_CLK_GATE(1, 15)
#define FCLK_CM0S_PMU		RK3399_CLK_GATE(2, 0)
#define SCLK_CM0S_PMU		RK3399_CLK_GATE(2, 1)
#define HCLK_CM0S_PMU		RK3399_CLK_GATE(2, 2)
#define DCLK_CM0S_PMU		RK3399_CLK_GATE(2, 3)

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_RK3399_CRU_H_ */
